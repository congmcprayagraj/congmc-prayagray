#!/usr/bin/env python3
"""
Regenerates data/gallery-manifest.js by scanning the real gallery/ folder.

Run from the repository root whenever you add/rename photos or folders:

    python3 tools/generate_gallery_manifest.py

Then commit data/gallery-manifest.js together with your new photos.
Nothing is moved, renamed or deleted: the script only READS gallery/.

Why this exists: GitHub Pages is static, so the browser cannot list folders.
This script (run on your computer) builds the list the website reads.
"""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GALLERY_DIR = os.path.join(ROOT, "gallery")
OUT_FILE = os.path.join(ROOT, "data", "gallery-manifest.js")
IMAGE_EXT = {".jpg", ".jpeg", ".png", ".webp", ".gif", ".avif"}

# Optional: nicer display names. Key = exact folder name on disk (case-sensitive).
TITLE_OVERRIDES = {
    "ganesh chathurti": "Ganesh Chaturthi",
}
# Optional: order of top-level albums (folder names). Anything not listed follows A-Z.
TOP_LEVEL_ORDER = [
    "freshers-party", "ganesh chathurti", "holi", "independence-day",
    "nursing-activities", "republic-day", "special-events",
]
# Optional: choose a specific cover photo. Key = relative folder path, value = file name.
COVER_OVERRIDES = {}


def natural_key(s):
    return [int(t) if t.isdigit() else t.lower() for t in re.split(r"(\d+)", s)]


def pretty(name):
    if name in TITLE_OVERRIDES:
        return TITLE_OVERRIDES[name]
    words = re.sub(r"[-_]+", " ", name).split()
    return " ".join(w[:1].upper() + w[1:] for w in words)


def scan(abs_dir, rel):
    photos, folders = [], []
    for entry in sorted(os.listdir(abs_dir), key=natural_key):
        full = os.path.join(abs_dir, entry)
        if os.path.isdir(full):
            if entry.startswith("."):
                continue
            folders.append(scan(full, rel + [entry]))
        elif os.path.splitext(entry)[1].lower() in IMAGE_EXT:
            photos.append(entry)
    node = {"name": rel[-1] if rel else "", "title": pretty(rel[-1]) if rel else "Gallery"}
    cover = COVER_OVERRIDES.get("/".join(rel))
    if cover:
        node["cover"] = cover
    node["photos"] = photos
    node["folders"] = folders
    return node


def main():
    if not os.path.isdir(GALLERY_DIR):
        sys.exit("gallery/ folder not found at " + GALLERY_DIR)
    tree = scan(GALLERY_DIR, [])
    rank = {n: i for i, n in enumerate(TOP_LEVEL_ORDER)}
    tree["folders"].sort(key=lambda f: (rank.get(f["name"], 999), natural_key(f["name"])))
    os.makedirs(os.path.dirname(OUT_FILE), exist_ok=True)
    with open(OUT_FILE, "w", encoding="utf-8") as fh:
        fh.write("/* AUTO-GENERATED by tools/generate_gallery_manifest.py — do not edit by hand.\n"
                 "   Re-run the script after adding photos/folders. Folder names are exact (case-sensitive). */\n")
        fh.write("window.GALLERY_MANIFEST = ")
        json.dump(tree, fh, indent=2, ensure_ascii=False)
        fh.write(";\n")

    def count(n):
        return len(n["photos"]) + sum(count(c) for c in n["folders"])
    print("Wrote", os.path.relpath(OUT_FILE, ROOT), "-", count(tree), "photos")
    for f in tree["folders"]:
        print("  %-22s %3d photos" % (f["title"], count(f)))


if __name__ == "__main__":
    main()

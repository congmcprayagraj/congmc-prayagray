/* gallery.js — event-wise nested gallery.
   • index.html  : shows a preview of the albums  (#galPreview)  -> links to gallery.html#album
   • gallery.html: full nested browser with breadcrumbs, deep links (#special-events/Earth-day) and one lightbox
   • any page    : points Facilities popup images at their real files inside gallery/
   Data: data/gallery-manifest.js (generated by tools/generate_gallery_manifest.py). No dependencies. */
(function () {
  'use strict';
  var ROOT = window.GALLERY_MANIFEST;
  var BASE = 'gallery/';
  var $ = function (id) { return document.getElementById(id); };
  var reduce = window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches;

  /* ---------- helpers ---------- */
  function plural(n, one, many) { return n + ' ' + (n === 1 ? one : many); }
  function count(node) { return node.photos.length + node.folders.reduce(function (s, f) { return s + count(f); }, 0); }
  function url(segs, file) { return BASE + segs.concat(file ? [file] : []).map(encodeURIComponent).join('/'); }
  function photoUrl(p, segs) {          // photo = "file.webp"  or  {file:"x.webp", dir:"special-events/Exact Folder"}
    if (typeof p === 'string') return url(segs, p);
    return url(String(p.dir || '').split('/').filter(Boolean), p.file);
  }
  function coverOf(node, segs) {        // explicit cover > first direct photo > first photo found in subfolders
    if (node.cover) return url(segs, node.cover);
    if (node.photos.length) return photoUrl(node.photos[0], segs);
    for (var i = 0; i < node.folders.length; i++) {
      var c = coverOf(node.folders[i], segs.concat(node.folders[i].name));
      if (c) return c;
    }
    return null;
  }
  function el(tag, cls, text) { var e = document.createElement(tag); if (cls) e.className = cls; if (text != null) e.textContent = text; return e; }
  function brokenImage(img, path) {
    img.addEventListener('error', function () {
      img.parentNode.classList.add('is-broken'); img.remove();
      if (window.console) console.warn('[gallery] image not found: ' + path);
    }, { once: true });
  }
  function safeDecode(s) { try { return decodeURIComponent(s); } catch (e) { return s; } }
  function findFile(node, segs, file) {
    for (var i = 0; i < node.photos.length; i++) {
      var ph = node.photos[i], f = typeof ph === 'string' ? ph : ph.file;
      if (f === file) return photoUrl(ph, segs);
    }
    for (var j = 0; j < node.folders.length; j++) {
      var hit = findFile(node.folders[j], segs.concat(node.folders[j].name), file);
      if (hit) return hit;
    }
    return null;
  }

  /* ---------- Facilities popup images (files now live inside gallery/) ---------- */
  var facImg = $('popupImage');
  if (ROOT && facImg) {
    Array.prototype.forEach.call(document.querySelectorAll('.facility-trigger'), function (card) {
      var f = card.getAttribute('data-image');
      var hit = f && findFile(ROOT, [], f);
      if (hit) card.setAttribute('data-image', hit);
    });
    facImg.addEventListener('error', function () {
      var src = facImg.getAttribute('src') || '';
      if (!src || src.indexOf(BASE) === 0) return;
      var hit = findFile(ROOT, [], safeDecode(src.split('/').pop()));
      if (hit) facImg.src = hit;
    });
  }
  if (!ROOT) { var s0 = $('galStage') || $('galPreview'); if (s0) s0.textContent = 'Gallery is unavailable right now.'; return; }

  /* ---------- album card (button inside the gallery page, link on the homepage) ---------- */
  function albumCard(child, segs, href, onOpen) {
    var total = count(child), empty = total === 0;
    var card = href ? el('a', 'gal-card') : el('button', 'gal-card' + (empty ? ' is-empty' : ''));
    if (href) card.href = href; else card.type = 'button';
    var media = el('span', 'gal-media');
    var cover = empty ? null : coverOf(child, segs);
    if (cover) {
      var img = new Image(); img.loading = 'lazy'; img.decoding = 'async';
      img.alt = child.title + ' album cover'; img.src = cover; brokenImage(img, cover); media.appendChild(img);
    } else media.appendChild(el('span', 'gal-soon', 'Photos coming soon'));
    var info = el('span', 'gal-info');
    info.appendChild(el('strong', 'gal-name', child.title));
    var bits = [plural(total, 'photo', 'photos')];
    if (child.folders.length) bits.push(plural(child.folders.length, 'album', 'albums'));
    info.appendChild(el('span', 'gal-count', empty ? 'No photos yet' : bits.join(' · ')));
    card.appendChild(media); card.appendChild(info);
    if (empty && !href) { card.disabled = true; card.setAttribute('aria-disabled', 'true'); }
    else if (onOpen) card.addEventListener('click', onOpen);
    return card;
  }

  /* ---------- homepage preview ---------- */
  var preview = $('galPreview');
  if (preview) {
    var lim = parseInt(preview.getAttribute('data-limit') || '6', 10);
    ROOT.folders.filter(function (f) { return count(f) > 0; }).slice(0, lim).forEach(function (f) {
      preview.appendChild(albumCard(f, [f.name], 'gallery.html#' + encodeURIComponent(f.name)));
    });
    if (!preview.children.length) preview.appendChild(el('p', 'nb-empty', 'Photo albums will appear here soon.'));
  }

  var elCrumb = $('galBreadcrumb'), elBar = $('galToolbar'), elBack = $('galBack'), elTitle = $('galTitle'),
      elMeta = $('galMeta'), elStage = $('galStage'), elFolders = $('galFolders'), elPhotosHead = $('galPhotosHead'),
      elPhotos = $('galPhotos'), section = $('gallery');
  if (!elStage) return;                                   // nothing more to do on pages without the full browser

  /* ---------- state lives in the URL hash (back button + shareable links) ---------- */
  var trail = [], baseTitle = document.title, userNav = false;
  function current() { return trail.length ? trail[trail.length - 1] : { node: ROOT, segs: [] }; }
  function syncFromHash(animate) {
    var names = location.hash.slice(1).split('/').filter(Boolean).map(safeDecode);
    var t = [], node = ROOT, segs = [];
    for (var i = 0; i < names.length; i++) {
      var child = null;
      for (var k = 0; k < node.folders.length; k++) if (node.folders[k].name === names[i]) { child = node.folders[k]; break; }
      if (!child) break;
      segs = segs.concat(child.name); t.push({ node: child, segs: segs.slice() }); node = child;
    }
    trail = t; render(animate);
    if (userNav) { userNav = false; bringIntoView(); }
  }
  function navigate(names) {
    userNav = true;
    if (names.length) location.hash = names.map(encodeURIComponent).join('/');
    else { if (location.hash) history.pushState(null, '', location.pathname + location.search); syncFromHash(true); }
  }
  function goTo(depth) { navigate(depth ? trail[depth - 1].segs : []); }
  window.addEventListener('hashchange', function () { syncFromHash(true); });

  /* ---------- rendering ---------- */
  function renderCrumbs() {
    elCrumb.innerHTML = '';
    var items = [{ label: 'Gallery', depth: 0 }].concat(trail.map(function (t, i) { return { label: t.node.title, depth: i + 1 }; }));
    items.forEach(function (it, i) {
      var last = i === items.length - 1;
      if (i) elCrumb.appendChild(el('span', 'gal-sep', '→'));
      if (last) { var s = el('span', 'gal-crumb is-current', it.label); s.setAttribute('aria-current', 'page'); elCrumb.appendChild(s); }
      else { var b = el('button', 'gal-crumb', it.label); b.type = 'button'; b.addEventListener('click', function () { goTo(it.depth); }); elCrumb.appendChild(b); }
    });
  }
  function render(animate) {
    var cur = current(), node = cur.node;
    renderCrumbs();
    var atRoot = trail.length === 0;
    elBar.hidden = atRoot;
    document.title = atRoot ? baseTitle : node.title + ' | Gallery | College of Nursing GMC Prayagraj';
    if (!atRoot) {
      elTitle.textContent = node.title;
      var meta = [plural(count(node), 'photo', 'photos')];
      if (node.folders.length) meta.push(plural(node.folders.length, 'album', 'albums'));
      elMeta.textContent = meta.join(' · ');
      elBack.textContent = '← Back to ' + (trail.length > 1 ? trail[trail.length - 2].node.title : 'Gallery');
    }
    elFolders.innerHTML = '';
    node.folders.forEach(function (child) {
      var segs = cur.segs.concat(child.name);
      elFolders.appendChild(albumCard(child, segs, null, function () { navigate(segs); }));
    });
    elFolders.hidden = !node.folders.length;

    elPhotos.innerHTML = '';
    var hasPhotos = node.photos.length > 0;
    elPhotosHead.hidden = !(hasPhotos && node.folders.length);
    elPhotosHead.textContent = hasPhotos ? 'Photos (' + node.photos.length + ')' : '';
    elPhotos.hidden = !hasPhotos;
    node.photos.forEach(function (ph, i) {
      var src = photoUrl(ph, cur.segs);
      var b = el('button', 'gal-photo'); b.type = 'button';
      b.setAttribute('aria-label', 'Open photo ' + (i + 1) + ' of ' + node.photos.length);
      var img = new Image(); img.loading = 'lazy'; img.decoding = 'async';
      img.alt = node.title + ' photograph ' + (i + 1); img.src = src; brokenImage(img, src);
      b.appendChild(img);
      b.addEventListener('click', function () { openViewer(i, b); });
      elPhotos.appendChild(b);
    });
    if (animate && !reduce) { elStage.classList.remove('gal-enter'); void elStage.offsetWidth; elStage.classList.add('gal-enter'); }
  }
  function bringIntoView() {
    if (!section) return;
    var top = section.getBoundingClientRect().top;
    if (top < 0 || top > window.innerHeight * 0.5) section.scrollIntoView({ behavior: reduce ? 'auto' : 'smooth', block: 'start' });
  }
  elBack.addEventListener('click', function () { goTo(trail.length - 1); });

  /* ---------- lightbox ---------- */
  var box = $('galleryLightbox'), boxImg = $('galleryLightboxImage'), boxCount = $('galleryCounter'),
      btnClose = $('galleryClose'), btnPrev = $('galleryPrev'), btnNext = $('galleryNext');
  var items = [], idx = 0, lastTrigger = null, sx = 0, sy = 0, multi = false;
  function show(i) {
    idx = (i + items.length) % items.length;
    boxImg.classList.remove('is-ready');
    boxImg.onload = function () { boxImg.classList.add('is-ready'); };
    boxImg.src = items[idx].src; boxImg.alt = items[idx].alt;
    boxCount.textContent = (idx + 1) + ' / ' + items.length;
    var many = items.length > 1; btnPrev.hidden = btnNext.hidden = !many;
    if (many) [idx + 1, idx - 1].forEach(function (n) { var p = new Image(); p.src = items[(n + items.length) % items.length].src; });
  }
  function openViewer(i, trigger) {
    var cur = current();
    items = cur.node.photos.map(function (f, n) { return { src: photoUrl(f, cur.segs), alt: cur.node.title + ' photograph ' + (n + 1) }; });
    lastTrigger = trigger || null; show(i);
    box.classList.add('active'); box.setAttribute('aria-hidden', 'false');
    document.body.classList.add('lightbox-open'); btnClose.focus();
  }
  function closeViewer() {
    if (!box.classList.contains('active')) return;
    box.classList.remove('active'); box.setAttribute('aria-hidden', 'true'); boxImg.removeAttribute('src');
    document.body.classList.remove('lightbox-open');
    if (lastTrigger && document.body.contains(lastTrigger)) lastTrigger.focus();
  }
  btnClose.addEventListener('click', closeViewer);
  btnNext.addEventListener('click', function () { show(idx + 1); });
  btnPrev.addEventListener('click', function () { show(idx - 1); });
  box.addEventListener('click', function (e) {
    if (e.target === box || e.target.classList.contains('gallery-lightbox-content')) closeViewer();
  });
  document.addEventListener('keydown', function (e) {
    if (!box.classList.contains('active')) return;
    if (e.key === 'Escape') closeViewer();
    else if (e.key === 'ArrowRight' && items.length > 1) show(idx + 1);
    else if (e.key === 'ArrowLeft' && items.length > 1) show(idx - 1);
    else if (e.key === 'Tab') {
      var f = [btnClose, btnPrev, btnNext].filter(function (b) { return !b.hidden; });
      var pos = f.indexOf(document.activeElement); e.preventDefault();
      f[(pos + (e.shiftKey ? -1 : 1) + f.length) % f.length].focus();
    }
  });
  box.addEventListener('touchstart', function (e) { multi = e.touches.length > 1; sx = e.changedTouches[0].clientX; sy = e.changedTouches[0].clientY; }, { passive: true });
  box.addEventListener('touchend', function (e) {
    if (multi || items.length < 2) return;
    var dx = e.changedTouches[0].clientX - sx, dy = e.changedTouches[0].clientY - sy;
    if (Math.abs(dx) > 50 && Math.abs(dx) > Math.abs(dy) * 1.2) show(dx < 0 ? idx + 1 : idx - 1);
  }, { passive: true });

  syncFromHash(false);
})();
